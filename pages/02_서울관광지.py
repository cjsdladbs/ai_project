# 3. 폴리움 지도 생성 (기본 OpenStreetMap 사용으로 또렷한 한국어와 선명한 색상 유지)
m = folium.Map(location=[37.555, 126.992], zoom_start=11.5, tiles="OpenStreetMap")

# 4. 지도 위에 커스텀 빨간색 마커 장식
for spot in seoul_spots:
    tooltip_text = f"🚇 가장 가까운 역: {spot['subway']}"
    
    icon_html = """
    <div style="
        background-color: #FF0032; 
        width: 18px; 
        height: 18px; 
        border-radius: 50%; 
        border: 2px solid #FFFFFF;
        box-shadow: 0px 0px 6px rgba(0,0,0,0.5);">
    </div>
    """
    
    folium.Marker(
        location=[spot['lat'], spot['lng']],
        popup=spot['name'],
        tooltip=tooltip_text,
        icon=folium.DivIcon(html=icon_html, icon_size=(18, 18))
    ).add_to(m)

# 5. 스트림릿에 기존의 약 60% 크기로 지도 렌더링 (가로 420, 세로 300)
# 중앙 정렬을 위해 3개의 컬럼 레이아웃 활용
col1, col2, col3 = st.columns([1, 3, 1])
with col2:
    st_folium(m, width=420, height=300)

st.markdown("---")

